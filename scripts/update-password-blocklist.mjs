import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";

// Review both pins before updating this offline dataset. Never run during startup.
const revision = "1a7bb9127eca9e6ff2fc0301c597fe6e16a0cb56";
const checksum =
  "c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0";
const base = `https://raw.githubusercontent.com/danielmiessler/SecLists/${revision}`;
const source = `${base}/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt`;
async function download(url) {
  const response = await globalThis.fetch(url, {
    signal: globalThis.AbortSignal.timeout(15000),
  });
  if (!response.ok)
    throw new Error(`Blocklist download failed: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}
const bytes = await download(source);
if (createHash("sha256").update(bytes).digest("hex") !== checksum)
  throw new Error("Blocklist checksum mismatch; no files changed.");
const license = (await download(`${base}/LICENSE`)).toString("utf8").trim();
const passwords = [
  ...new Set(
    bytes
      .toString("utf8")
      .split(/\r?\n/)
      .map((value) => value.normalize("NFC").toLowerCase())
      .filter((value) => [...value].length >= 15 && [...value].length <= 128),
  ),
].sort();
const header = `/*\nGenerated by scripts/update-password-blocklist.mjs. Do not edit the corpus manually.\nNCSC/HIBP top-password snapshot, mirrored by SecLists.\nSource: ${source}\nSource SHA-256: ${checksum}\nOnly full passwords within the accepted 15–128 code point range are retained.\nShorter values are already rejected by the minimum length policy.\n\n${license}\n*/\n`;
await writeFile(
  new URL("../apps/backend/src/auth/password-blocklist.ts", import.meta.url),
  header +
    `export const blockedPasswords: ReadonlySet<string> = new Set([\n${passwords.map((value) => `  ${JSON.stringify(value)},`).join("\n")}\n]);\n`,
);
process.stdout.write(
  `Generated offline blocklist with ${passwords.length} entries; source checksum verified.\n`,
);
